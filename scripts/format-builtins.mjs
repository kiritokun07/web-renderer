import { writeFile } from "node:fs/promises";
import { templates } from "../templates.js";
import { formatCode } from "../formatter-source.js";

async function formatProject(source) {
  return Object.fromEntries(await Promise.all(["html", "css", "js"].map(async language => [language, await formatCode(source[language], language)])));
}

export async function buildBuiltinCode() {
  const code = {
    templates: {},
  };
  for (const template of templates) {
    code.templates[template.id] = {};
    for (const language of ["zh", "en"]) code.templates[template.id][language] = await formatProject(template.code(language));
  }
  code.example = code.templates.garden.zh;
  code.blank = code.templates.blank.zh;
  await writeFile(new URL("../builtin-code.js", import.meta.url), `// Generated by npm run build. Edit templates.js or templates/ to change built-in projects.\nexport const builtinCode = ${JSON.stringify(code, null, 2)};\n`);
}
